"""Writes a planned workspace to disk: repositories, conversation history,
avatars and plan.json, which the Rust appliers turn into the app's stores."""

import binascii
import json
import os
import shutil
import struct
import time
import zlib

from . import claude, codex, repositories
from .determinism import iso
from .workspace import Planner

# The plan's own format. The Rust appliers refuse any other, so bump it with
# every change they must understand, in the same commit as theirs.
PLAN_FORMAT = 1
MARKER = "plan.json"
# Written first, so a generation that failed partway can still be replaced.
OWNER = ".fixture-workspace"


def prepare_root(root, replace):
    if os.path.lexists(root) and os.listdir(root):
        if not replace:
            raise SystemExit(f"{root} is not empty. Pass --replace to regenerate a workspace generated there before.")
        if not os.path.isfile(os.path.join(root, OWNER)):
            raise SystemExit(f"{root} holds no {OWNER}, so it was not generated here; refusing to delete it.")
        shutil.rmtree(root)
    os.makedirs(root, exist_ok=True)
    with open(os.path.join(root, OWNER), "w") as file:
        file.write("Generated by scripts/fixture-workspace; `generate --replace` may delete this directory.\n")


def png(color, size=64):
    """A small square avatar: a solid color with a lighter diagonal band."""
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            band = abs(x - y) < size // 6
            row += bytes(min(255, c + 60) if band else c for c in color)
        rows.append(bytes(row))
    raw = zlib.compress(b"".join(rows), 9)

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", binascii.crc32(kind + data))

    header = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", raw) + chunk(b"IEND", b"")


def generate(profile, seed, root, epoch, replace=False, log=print):
    root = os.path.realpath(root)
    prepare_root(root, replace)
    started = time.monotonic()
    planner = Planner(profile, seed, root, epoch).plan()
    os.makedirs(os.path.join(root, "bin"), exist_ok=True)
    os.makedirs(os.path.join(root, "home"), exist_ok=True)
    for project in planner.projects:
        repositories.create(root, project, epoch)
    timings = {"repositories": time.monotonic() - started}

    mark = time.monotonic()
    home = planner.home
    os.makedirs(os.path.join(home, ".claude", "projects"), exist_ok=True)
    stream = planner.streams("claude-records")
    written = {}
    claude_summary = []
    # A fork copies its origin's records, so origins are written first.
    for spec in sorted(planner.claude, key=lambda s: s.get("edge") == "forked"):
        if spec.get("edge") == "forked":
            spec["origin_lines"], spec["origin_shown"] = written[spec["origin"]]
        result = claude.write(home, spec, stream)
        written[spec["session_id"]] = (result["lines"], result["shown"])
        if result["details"]:
            planner.edge_detail(spec, result["details"])
        claude_summary.append({"session_id": spec["session_id"], "file": result["path"], "cwd": spec["cwd"],
                               "edge": spec.get("edge"), "visible": result["visible"],
                               "subagents": result["subagents"], "title": spec["title"]})
    timings["claude"] = time.monotonic() - mark

    mark = time.monotonic()
    codex_home = os.path.join(home, ".codex")
    stream = planner.streams("codex-records")
    codex_summary = []
    names = []
    latest = None
    for spec in planner.codex:
        result = codex.write(codex_home, spec, stream)
        latest = max(latest or result["ended_at"], result["ended_at"])
        if spec["name"] and "parent" not in spec:
            names.append({"id": spec["thread_id"], "thread_name": spec["name"], "updated_at": iso(result["ended_at"])})
        codex_summary.append({"thread_id": spec["thread_id"], "file": result["path"], "cwd": spec["cwd"],
                              "turns": result["turns"], "subagent": "parent" in spec,
                              "archived": spec.get("archived", False), "name": spec["name"]})
    codex.write_index(codex_home, names, latest or epoch)
    timings["codex"] = time.monotonic() - mark

    for project in planner.projects:
        if project["avatar"]:
            os.makedirs(os.path.join(root, "avatars"), exist_ok=True)
            with open(os.path.join(root, "avatars", f"{project['avatar']['owner']}.png"), "wb") as file:
                file.write(png(project["avatar"]["color"]))

    plan = {
        "format": PLAN_FORMAT,
        "profile": profile.name,
        "seed": seed,
        "epoch": epoch,
        "root": root,
        "home": home,
        "edge_cases": planner.edge_cases,
        "operation_namespace": planner.streams("operations").uuid4(),
        "environments": planner.environments,
        "projects": [{key: project[key] for key in
                      ("id", "name", "checkout", "repository", "worktrees", "historical", "avatar", "remote", "dirty")}
                     for project in planner.projects],
        "cards": planner.cards,
        "channels": planner.channels,
        "views": [{"scope": view["scope"], "panes": view["panes"], "retired": view["retired"],
                   "edits": view["edits"]} for view in planner.views],
        "windows": planner.windows,
        "history": {"claude": claude_summary, "codex": codex_summary, "writer_locks": planner.writer_locks},
    }
    with open(os.path.join(root, MARKER), "w") as file:
        json.dump(plan, file, indent=1, sort_keys=True)
        file.write("\n")
    timings["total"] = time.monotonic() - started
    log(summary(plan, timings))
    return plan


def summary(plan, timings):
    cards = plan["cards"]
    open_cards = sum(card["closed_at_ms"] is None for card in cards)
    views = plan["views"]
    return (f"Generated the {plan['profile']} workspace (seed {plan['seed']}) at {plan['root']} in "
            f"{timings['total']:.1f}s: {len(plan['projects'])} projects, {len(plan['channels'])} channels, "
            f"{len(cards)} cards ({open_cards} open), {len(views)} shared views "
            f"({sum(bool(v['panes']) for v in views)} with panes, {sum(v['edits'] for v in views)} recorded edits), "
            f"{len(plan['history']['claude'])} Claude and {len(plan['history']['codex'])} Codex conversations.")
